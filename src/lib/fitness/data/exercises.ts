/** Search the exercise library by free text (name or muscle, case-insensitive)
 *  with optional muscle / equipment / type filters. */
export function searchExercises(
  q: string,
  filters?: { muscle?: MuscleId; equipment?: Equipment; type?: ExerciseType },
): Exercise[] {
  const query = q.trim().toLowerCase();
  return EXERCISES.filter((ex) => {
    if (filters?.type && ex.type !== filters.type) return false;
    if (filters?.equipment && !ex.equipment.includes(filters.equipment)) return false;
    if (
      filters?.muscle &&
      !ex.muscles.includes(filters.muscle) &&
      !ex.secondary.includes(filters.muscle)
    ) {
      return false;
    }
    if (!query) return true;
    if (ex.name.toLowerCase().includes(query)) return true;
    return [...ex.muscles, ...ex.secondary].some(
      (m) => m.includes(query) || MUSCLE_MAP[m].label.toLowerCase().includes(query),
    );
  });
}
