// ENERGY POLICY — every kcal is Atwater-consistent with the macro trio:
//   kcal ≈ 4×protein + 4×carbs + 9×fat   (dietary fibre contributes ~0)
// Where a source publishes macros alongside a specific-factor / measured energy
// that diverges from general 4-4-9 (meats use 4.27/8.79 protein/fat factors,
// nuts & seeds use measured energy, produce sugars use ~3.87 kcal/g), the macros
// are kept inside the published range and kcal follows the 4-4-9 formula so the
// app's arithmetic always reconciles. Documented exceptions:
//   · beer / red wine — ethanol supplies 7 kcal/g and is not a tracked macro,
//     so 4-4-9 under-counts these by design (kcal = published value)
//   · sugar 387 & oils 884 — USDA metabolisable-energy factors (3.87 kcal/g
//     sucrose, 8.84 kcal/g oil); crude 4-4-9 would give 399 / 900
//
// Serving weights follow USDA household measures / Indian household conventions
// (katori ≈ 150 g, roti 35 g, chai cup 150 ml). Beverage servings carry ml in
// the label; the `grams` field holds the same number (1 ml ≈ 1 g).

