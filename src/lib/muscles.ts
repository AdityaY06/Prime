// ── Name normalization & mapping ──────────────────────────────────────────────

/** Lowercase, trim, collapse whitespace, strip apostrophes/quotes, and turn separators into spaces. */
export function normalizeName(s: string): string {
  return s
    .toLowerCase()
    .replace(/[\u2018\u2019\u02bc`"']/g, "")
    .replace(/[\u2013\u2014\-_/\\]/g, " ")
    .replace(/[.,:;!?()&+]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
}

/** Exact (normalized) match of an exercise name against the library, by name or alias. */
export function mapExerciseToMuscles(
  name: string
): { primary: MuscleId[]; secondary: MuscleId[] } | null {
  const key = normalizeName(name)
  if (!key) return null
  for (const ex of EXERCISE_LIBRARY) {
    if (normalizeName(ex.name) === key || ex.aliases.some((a) => normalizeName(a) === key)) {
      return { primary: [...ex.muscles.primary], secondary: [...ex.muscles.secondary] }
    }
  }
  return null
}

// ── Equipment-variant swap intelligence (R6-a) ───────────────────────────────

/** Resolve a library entry by id or exact normalized name/alias (mirror of mapExerciseToMuscles matching). */
function findExerciseDef(idOrName: string): ExerciseDef | null {
  if (!idOrName) return null
  for (const ex of EXERCISE_LIBRARY) {
    if (ex.id === idOrName) return ex
  }
  const key = normalizeName(idOrName)
  if (!key) return null
  for (const ex of EXERCISE_LIBRARY) {
    if (normalizeName(ex.name) === key || ex.aliases.some((a) => normalizeName(a) === key)) {
      return ex
    }
  }
  return null
}

/** Same-movement-pattern alternatives for an exercise (by id or name); missing ids are filtered defensively. */
export function variantsFor(idOrName: string): ExerciseDef[] {
  const src = findExerciseDef(idOrName)
  if (!src?.variants?.length) return []
  const out: ExerciseDef[] = []
  for (const id of src.variants) {
    const v = EXERCISE_LIBRARY.find((e) => e.id === id)
    if (v && v.id !== src.id) out.push(v)
  }
  return out
}

/** Movement-pattern label derived from the primary muscles — used for swap-line suffixes. */
function patternLabelFor(ex: ExerciseDef): string {
  const p = ex.muscles.primary
  if (p.includes("lats")) return "PULL"
  if (p.includes("chest") || p.includes("triceps") || p.includes("shoulders")) return "PRESS"
  if (p.includes("biceps")) return "CURL"
  if (p.includes("hamstrings") || p.includes("lower-back")) return "HINGE"
  if (p.includes("quads")) return "SQUAT"
  if (p.includes("glutes")) return "HIP-HINGE"
  if (p.includes("calves")) return "CALF"
  if (p.includes("traps") && p.includes("forearms")) return "CARRY"
  if (p.includes("traps")) return "SHRUG"
  if (p.includes("core")) return "CORE"
  if (p.includes("forearms")) return "GRIP"
  return "MOVEMENT"
}

/** Max length for the swap line — keeps it readable in mono system chips. */
const SWAP_LINE_MAX = 90

/**
 * Short uppercase equipment-swap line for an equipment-dependent exercise, e.g.
 * "NO EQUIPMENT? → INVERTED ROW · BAND ROW (SAME PULL PATTERN)". Prefers true
 * bodyweight/no-equipment variants, then bands. Null when the exercise already
 * needs no equipment (or no equipment-free alternative exists).
 */
export function equipmentSwapLine(idOrName: string): string | null {
  const src = findExerciseDef(idOrName)
  if (!src) return null
  if (src.equipment === "bodyweight" || src.equipment === "none") return null
  const rank = (v: ExerciseDef) => (v.equipment === "band" ? 1 : 0)
  const picks = variantsFor(src.id)
    .filter((v) => v.equipment === "bodyweight" || v.equipment === "none" || v.equipment === "band")
    .sort((a, b) => rank(a) - rank(b))
  if (picks.length === 0) return null
  const pattern = ` (SAME ${patternLabelFor(src)} PATTERN)`
  for (let n = Math.min(2, picks.length); n >= 1; n--) {
    const names = picks
      .slice(0, n)
      .map((p) => p.name.toUpperCase())
      .join(" · ")
    const base = `NO EQUIPMENT? → ${names}`
    if (base.length + pattern.length <= SWAP_LINE_MAX) return base + pattern
    if (base.length <= SWAP_LINE_MAX) return base
  }
  const solo = `NO EQUIPMENT? → ${picks[0].name.toUpperCase()}`
  return solo.length <= SWAP_LINE_MAX ? solo : solo.slice(0, SWAP_LINE_MAX - 1) + "…"
}

// ── 1RM math ──────────────────────────────────────────────────────────────────

/** Epley estimated 1RM. Guarded: reps <= 0 → 0, reps >= 37 → treated as the weight itself.
 * R68: reps === 1 → the weight itself — a 1-rep set IS the measured 1RM (the
 * formula would add a spurious +3.3% to an actual maximum).
 * R69-a: the Epley core (r=1 pin + w×(1+r/30)) now delegates to
 * lib/strength-science.ts epleyE1rm — the single source of truth — with this
 * file's exact guard contract preserved byte-for-byte (un-rounded values,
 * legacy reps ≥ 37 pin included). One honest deviation: non-finite reps now
 * return 0 instead of propagating NaN through the formula. */
export function epley1RM(weight: number, reps: number): number {
  if (!Number.isFinite(weight) || weight <= 0) return 0
  if (reps <= 0) return 0
  if (reps >= 37) return weight
  // 1 ≤ reps < 37 at a positive finite load → the shared core
  // (r=1 identity pin and the Epley expression both live there)
  return epleyE1rm(weight, reps)
}

/**
 * Brzycki estimated 1RM (R69 — the raw core from lib/strength-science, the
 * single source of truth; citation: Brzycki M. 1993, JOPERD 64:88-90).
 * Guarded like its epley1RM sibling: 0 outside the honest 1-12 rep domain —
 * the legacy `reps ≥ 37 → the weight itself` branch is dead (that range
 * never had an estimate to return). Naturally exact at r=1 (36/36).
 */
export function brzycki1RM(weight: number, reps: number): number {
  if (!validE1rmSet(reps, weight)) return 0
  return (weight * 36) / (37 - reps)
}

/** Percentage-of-max table for [95,90,85,80,75,70,65,60,50]. */
export function repMaxTable(oneRM: number): { pct: number; weight: number }[] {
  const pcts = [95, 90, 85, 80, 75, 70, 65, 60, 50]
  return pcts.map((pct) => ({ pct, weight: Math.max(0, Math.round((oneRM * pct) / 100 * 100) / 100) }))
}

// ── Plate math ────────────────────────────────────────────────────────────────

export const STANDARD_PLATES = [25, 20, 15, 10, 5, 2.5, 1.25]

/**
 * Greedy per-side plate breakdown for a target total (bar included).
 * Returns null when the target cannot be built from standard plates.
 */
export function platesFor(
  targetKg: number,
  barKg: number
): { plate: number; count: number }[] | null {
  if (!Number.isFinite(targetKg) || !Number.isFinite(barKg) || targetKg < barKg || barKg < 0) {
    return null
  }
  let remaining = Math.round(((targetKg - barKg) / 2) * 100) / 100
  if (remaining < 0) return null
  const out: { plate: number; count: number }[] = []
  for (const p of STANDARD_PLATES) {
    const count = Math.floor(remaining / p + 1e-9)
    if (count > 0) {
      out.push({ plate: p, count })
      remaining = Math.round((remaining - count * p) * 100) / 100
    }
  }
  if (remaining > 0.005) return null
  return out
}

